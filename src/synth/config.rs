//! `anchor.toml`: every generated source with its trust level, data directory inside the output
//! and System 1 disabled, so the dataset ingests and queries with no model at all.

use std::path::Path;

use super::{
    Ctx, SOURCE_JIRA, SOURCE_LEGACY, SOURCE_ORG, SOURCE_PORTAL, SOURCE_REVIEWS, SOURCE_WIKI,
};
use crate::base::{Result, SourceKind, TrustLevel};
use crate::config::{AnchorConfig, SourceConfig};
use crate::engine::router::ProviderKind;

/// Builds the configuration for a dataset generated under `root` (an absolute path).
pub(crate) fn build(ctx: &Ctx, root: &Path) -> AnchorConfig {
    let location = |rel: &str| root.join(rel).to_string_lossy().into_owned();
    let mut config = AnchorConfig {
        data_dir: Some(root.join(".anchor")),
        ..AnchorConfig::default()
    };
    config.models.system1.provider = ProviderKind::Disabled;
    config.models.system2.provider = ProviderKind::Disabled;
    config.watcher.enabled = false;
    config.web.enabled = false;

    let mut push = |id: &str, kind: SourceKind, rel: &str, trust: TrustLevel, name: &str| {
        let mut source = SourceConfig::new(id, kind, location(rel));
        source.trust = trust;
        source.name = Some(name.to_owned());
        config.sources.push(source);
    };
    push(
        SOURCE_ORG,
        SourceKind::OrgModel,
        "org",
        TrustLevel::SourceOfTruth,
        "Enterprise organisation model",
    );
    if ctx
        .plan
        .services
        .iter()
        .any(|s| s.stale_team.is_some() || s.reference_team.is_some())
    {
        push(
            SOURCE_LEGACY,
            SourceKind::OrgModel,
            "legacy",
            TrustLevel::ReferenceOnly,
            "Legacy directory export (stale)",
        );
    }
    for service in &ctx.plan.services {
        push(
            &service.slug,
            SourceKind::Repo,
            &format!("repos/{}", service.slug),
            TrustLevel::SourceOfTruth,
            &service.slug,
        );
    }
    if ctx.report.apis > 0 {
        push(
            SOURCE_PORTAL,
            SourceKind::ApiPortal,
            "portal",
            TrustLevel::SourceOfTruth,
            "API approval portal",
        );
    }
    if ctx.report.wiki_pages > 0 {
        push(
            SOURCE_WIKI,
            SourceKind::Wiki,
            "wiki",
            TrustLevel::ReferenceOnly,
            "Engineering wiki",
        );
    }
    if ctx.report.tickets > 0 {
        push(
            SOURCE_JIRA,
            SourceKind::Jira,
            "jira",
            TrustLevel::ReferenceOnly,
            "Issue tracker",
        );
    }
    if ctx.report.pull_requests > 0 {
        push(
            SOURCE_REVIEWS,
            SourceKind::CodeReview,
            "reviews",
            TrustLevel::ReferenceOnly,
            "Code reviews",
        );
    }
    config
}

pub(crate) fn emit(ctx: &mut Ctx, root: &Path) -> Result<()> {
    let config = build(ctx, root);
    let text = format!(
        "# Generated by `anchor demo`: a synthetic enterprise. Safe to delete.\n{}",
        config.to_toml_string()?
    );
    ctx.out.write("config", "anchor.toml", &text)
}
